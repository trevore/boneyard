#!/bin/bash
# Set up this Mac: packages, shell config, starship, vim.
# Safe to re-run. Differing existing files are moved aside (*.bak.<time>) first.
set -eu

DIR="$(cd "$(dirname "$0")" && pwd)"

# On Apple Silicon brew isn't on PATH until shellenv is evaluated
# shellcheck disable=SC2016  # literal line to write to ~/.zprofile
BREW_ENV='eval "$(/opt/homebrew/bin/brew shellenv)"'
if ! command -v brew >/dev/null && [ -x /opt/homebrew/bin/brew ]; then
  eval "$(/opt/homebrew/bin/brew shellenv)"
  grep -qxF "$BREW_ENV" ~/.zprofile 2>/dev/null || echo "$BREW_ENV" >> ~/.zprofile
fi

if ! command -v brew >/dev/null; then
  echo "Install Homebrew first: https://brew.sh" >&2
  exit 1
fi

brew bundle --file="$DIR/Brewfile"

# Copy $1 (file in this repo) to $2. A different existing file is backed up first.
install_file() {
  mkdir -p "$(dirname "$2")"
  [ -L "$2" ] && rm "$2"  # never write through a symlink (e.g. into the repo)
  if [ -e "$2" ] && ! cmp -s "$1" "$2"; then
    mv "$2" "$2.bak.$(date +%s)"
    echo "backed up $2 -> $2.bak.*"
  fi
  cp "$1" "$2"
  echo "installed $2"
}

# Starship has no include mechanism, so build its config from the repo file plus
# an optional ~/.config/starship.local.toml that this script never touches.
# (TOML forbids redefining a table, so local additions can't repeat one from the repo file.)
STARSHIP_TMP="$(mktemp)"
{
  echo "# Generated by mac/install.sh. Edit starship.toml in the repo or ~/.config/starship.local.toml, not this file."
  cat "$DIR/starship.toml"
  if [ -r ~/.config/starship.local.toml ]; then
    echo
    cat ~/.config/starship.local.toml
  fi
} > "$STARSHIP_TMP"
install_file "$STARSHIP_TMP" ~/.config/starship.toml
rm "$STARSHIP_TMP"
install_file "$DIR/vimrc" ~/.vimrc
install_file "$DIR/zshrc" ~/.zshrc.mac
mkdir -p ~/.vim/backup ~/.vim/tmp

# Load ~/.zshrc.mac from ~/.zshrc (once)
# shellcheck disable=SC2016  # literal line to write to ~/.zshrc
LINE='[ -r ~/.zshrc.mac ] && source ~/.zshrc.mac'
grep -qxF "$LINE" ~/.zshrc 2>/dev/null || echo "$LINE" >> ~/.zshrc

# vim-airline via Vim's built-in package loading
AIRLINE=~/.vim/pack/plugins/start/vim-airline
if [ -d "$AIRLINE" ]; then
  git -C "$AIRLINE" pull --quiet
else
  git clone --depth 1 https://github.com/vim-airline/vim-airline "$AIRLINE"
fi

cat <<'EOF'

Done. Two manual steps:
  1. iTerm2 -> Settings -> Profiles -> Text -> Font: JetBrainsMono Nerd Font
  2. Open a new terminal tab (or: source ~/.zshrc)
EOF
