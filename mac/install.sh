#!/bin/bash
# Set up this Mac: packages, shell config, starship, vim, iTerm2 profile, macOS settings.
# Safe to re-run. A differing existing file is moved aside (*.bak.<time>) first,
# except the files this script generates itself (see MARKER below).
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"

# Append line $1 to file $2 unless it's already there
append_once() {
  grep -qxF "$1" "$2" 2>/dev/null && return
  # Start on a new line if the file doesn't end with one
  if [ -s "$2" ] && [ -n "$(tail -c1 "$2")" ]; then echo >> "$2"; fi
  echo "$1" >> "$2"
}

# On Apple Silicon brew isn't on PATH until shellenv is evaluated
if ! command -v brew >/dev/null && [ -x /opt/homebrew/bin/brew ]; then
  eval "$(/opt/homebrew/bin/brew shellenv)"
  # shellcheck disable=SC2016  # literal line to write to ~/.zprofile
  append_once 'eval "$(/opt/homebrew/bin/brew shellenv)"' ~/.zprofile
fi

if ! command -v brew >/dev/null; then
  echo "Install Homebrew first: https://brew.sh" >&2
  exit 1
fi

brew bundle --file="$DIR/Brewfile"

# First line of the files this script generates. They say not to edit them, so they're
# replaced without a backup.
MARKER="# Generated by mac/install.sh"

# Copy $1 to $2. A different existing file is backed up first, unless we generated it.
install_file() {
  mkdir -p "$(dirname "$2")"
  [ -L "$2" ] && rm "$2"  # never write through a symlink (e.g. into the repo)
  if [ -e "$2" ] && ! cmp -s "$1" "$2"; then
    case "$(head -n1 "$2")" in
      "$MARKER"*) ;;
      *) mv "$2" "$2.bak.$(date +%s)"
         echo "backed up $2 -> $2.bak.*" ;;
    esac
  fi
  cp "$1" "$2"
  echo "installed $2"
}

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

# Starship has no include mechanism, so build its config from three parts:
#   1. ~/.config/starship.local.toml, if present (this script never touches it).
#      It goes first so any top-level keys in it stay top-level.
#   2. starship's nerd-font-symbols preset (minus its top-level "$schema" line, for the same reason)
#   3. this repo's starship.toml, merged in: the preset already defines some of the same
#      tables and TOML forbids repeating a table, so each repo key is inserted under the
#      preset's matching [table] header, and tables the preset lacks are added at the end.
# So: the repo file must be tables only, and the local file can't repeat any table.
{
  echo "$MARKER. Edit starship.toml in the repo or ~/.config/starship.local.toml, not this file."
  if [ -r ~/.config/starship.local.toml ]; then
    cat ~/.config/starship.local.toml
    echo
  fi
  starship preset nerd-font-symbols | awk '
    FNR == NR { if (/^\[/) t = $0; else if (NF && !/^#/) keys[t] = keys[t] $0 "\n"; next }
    /^"\$schema"/ { next }
    { print }
    /^\[/ && ($0 in keys) { printf "%s", keys[$0]; delete keys[$0] }
    END { for (t in keys) printf "\n%s\n%s", t, keys[t] }
  ' "$DIR/starship.toml" -
} > "$TMP"
# starship exits 0 even on a broken config, but reports problems on stderr
ERRS="$(STARSHIP_CONFIG="$TMP" starship print-config 2>&1 >/dev/null)"
if [ -n "$ERRS" ]; then
  echo "Generated starship config has errors, so it wasn't installed." >&2
  echo "Check mac/starship.toml and ~/.config/starship.local.toml (rules: comments in mac/install.sh)." >&2
  echo "$ERRS" >&2
  exit 1
fi
install_file "$TMP" ~/.config/starship.toml

{
  echo "$MARKER. Edit zshrc in the repo, or ~/.zshrc for this machine only, not this file."
  cat "$DIR/zshrc"
} > "$TMP"
install_file "$TMP" ~/.zshrc.mac

install_file "$DIR/vimrc" ~/.vimrc
mkdir -p ~/.vim/backup ~/.vim/tmp

# iTerm2 picks up profiles in this folder automatically, including while it's running.
# Plain copy, no backup: iTerm2 loads every file in the folder, so a backup there would
# be a second profile with the same Guid. iTerm2 can't edit these, so there's nothing to keep.
ITERM_PROFILES=~/Library/Application\ Support/iTerm2/DynamicProfiles
mkdir -p "$ITERM_PROFILES"
cp "$DIR/iterm2-profile.json" "$ITERM_PROFILES/boneyard.json"
echo "installed $ITERM_PROFILES/boneyard.json"

"$DIR/defaults.sh"

# Load ~/.zshrc.mac from ~/.zshrc
append_once '[ -r ~/.zshrc.mac ] && source ~/.zshrc.mac' ~/.zshrc

# vim-airline via Vim's built-in package loading
AIRLINE=~/.vim/pack/plugins/start/vim-airline
if [ -d "$AIRLINE" ]; then
  git -C "$AIRLINE" pull --quiet
else
  git clone --depth 1 https://github.com/vim-airline/vim-airline "$AIRLINE"
fi

cat <<'EOF'

Done. Manual steps:
  1. iTerm2 -> Settings -> Profiles -> select "Boneyard" -> Other Actions -> Set as Default
  2. Open a new terminal tab (or: source ~/.zshrc)
  3. Log out and back in for dark mode and scroll direction
EOF
